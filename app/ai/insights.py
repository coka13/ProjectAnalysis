def _refactor_fallback(findings: dict[str, Any], language: str) -> dict[str, Any]:
    suggestions: list[dict[str, Any]] = []
    for cycle in findings["cycles"][:3]:
        suggestions.append(
            {
                "title": t(language, "improve_cycle"),
                "problem": t(language, "risk_cycle", modules=" → ".join(cycle)),
                "approach": t(language, "improve_abstraction"),
                "affected": cycle,
                "impact": "high",
                "effort": "M",
                "steps": [t(language, "improve_cycle"), t(language, "improve_abstraction")],
            }
        )
    for god in findings["god_classes"][:3]:
        suggestions.append(
            {
                "title": t(language, "improve_god"),
                "problem": t(language, "risk_god", name=god["name"], methods=god["methods"]),
                "approach": t(language, "improve_god"),
                "affected": [god["name"]],
                "impact": "medium",
                "effort": "L",
                "steps": [t(language, "improve_god")],
            }
        )
    for violation in findings["layering_violations"][:3]:
        suggestions.append(
            {
                "title": t(language, "improve_layer"),
                "problem": t(
                    language,
                    "risk_layer",
                    src=violation["from"],
                    src_layer=violation["from_layer"],
                    dst=violation["to"],
                    dst_layer=violation["to_layer"],
                ),
                "approach": t(language, "improve_layer"),
                "affected": [violation["from"], violation["to"]],
                "impact": "medium",
                "effort": "M",
                "steps": [t(language, "improve_layer")],
            }
        )
    if not suggestions:
        suggestions.append(
            {
                "title": t(language, "improve_docs"),
                "problem": t(language, "no_issue"),
                "approach": t(language, "improve_docs"),
                "affected": [],
                "impact": "low",
                "effort": "S",
                "steps": [t(language, "improve_docs")],
            }
        )
    return {
        "suggestions": suggestions,
        "target_architecture": t(language, "improve_abstraction"),
        "findings": findings,
        "source": "static",
    }


