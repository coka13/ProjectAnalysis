def _review_fallback(graph: KnowledgeGraph, metrics: dict[str, Any], language: str) -> dict[str, Any]:
    stats = graph.stats()
    languages = ", ".join(stats.get("files_by_language", {}).keys()) or "-"
    strengths: list[str] = []
    layers = {k: v for k, v in (metrics.get("layers") or {}).items() if k != "unassigned" and v}
    if len(layers) >= 3:
        strengths.append(t(language, "strength_layers", count=len(layers)))
    if (metrics.get("abstraction_ratio") or 0) >= 0.12:
        strengths.append(t(language, "strength_abstraction", ratio=metrics.get("abstraction_ratio")))
    if not metrics.get("cycles"):
        strengths.append(t(language, "strength_nocycle"))
    if any("test" in (node.module or "").lower() for node in graph.by_kind(NodeKind.FILE)):
        strengths.append(t(language, "strength_tests"))
    containers = len(graph.by_kind(NodeKind.CONTAINER))
    if containers:
        strengths.append(t(language, "strength_containers", count=containers))

    issues = [
        {"severity": risk["severity"], "area": risk.get("impact", ""), "issue": risk["issue"], "evidence": "static analysis"}
        for risk in _risks(metrics, language)
        if risk["issue"] != t(language, "no_issue")
    ]
    recommendations = [
        {"priority": index + 1, "title": item, "detail": item, "effort": "M"}
        for index, item in enumerate(_improvements(metrics, language))
    ]

    return {
        "summary": t(
            language,
            "summary",
            components=len(graph.by_kind(NodeKind.COMPONENT)),
            types=len(graph.by_kind(NodeKind.CLASS, NodeKind.INTERFACE, NodeKind.ABSTRACT_CLASS, NodeKind.STRUCT)),
            languages=languages,
            score=metrics.get("score", 0),
            grade=metrics.get("grade", "-"),
        ),
        "score": metrics.get("score", 0),
        "grade": metrics.get("grade", "-"),
        "strengths": strengths or [t(language, "no_issue")],
        "issues": issues,
        "recommendations": recommendations,
        "quick_wins": _improvements(metrics, language)[:2],
        "metrics": _slim_metrics(metrics),
        "source": "static",
    }


