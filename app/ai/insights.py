async def explain_diagram(
    graph: KnowledgeGraph,
    diagram: dict[str, Any],
    language: str = "en",
    provider: AIProvider | None = None,
) -> dict[str, Any]:
    fallback = _explain_fallback(graph, diagram, language)
    if provider is None:
        return fallback
    try:
        context = prompts.graph_summary(graph)
        parsed = await provider.chat_json(
            prompts.explain_diagram(diagram, context, language),
            max_tokens=max(provider.config.max_tokens, 3072),
        )
        parsed.setdefault("purpose", fallback["purpose"])
        parsed.setdefault("description", fallback["description"])
        parsed.setdefault("key_components", fallback["key_components"])
        parsed.setdefault("patterns", fallback["patterns"])
        parsed.setdefault("risks", fallback["risks"])
        parsed.setdefault("improvements", fallback["improvements"])
        parsed["source"] = "ai"
        return parsed
    except AIProviderError as exc:
        log.warning("diagram explanation via AI failed: %s", exc)
        fallback["warning"] = str(exc)
        return fallback


def _explain_fallback(graph: KnowledgeGraph, diagram: dict[str, Any], language: str) -> dict[str, Any]:
    payload = diagram.get("payload") or {}
    nodes = payload.get("nodes") or payload.get("entities") or payload.get("participants") or []
    edges = payload.get("edges") or payload.get("relations") or payload.get("steps") or []
    metrics = (graph.meta or {}).get("metrics", {})

    key_components = [
        {"name": node.get("name", ""), "role": node.get("responsibility") or node.get("kind", "")}
        for node in sorted(nodes, key=lambda n: -(n.get("methods", 0) or 0))[:6]
    ]
    patterns = [
        {"pattern": entry["pattern"], "evidence": entry["evidence"]}
        for entry in (metrics.get("patterns") or [])[:5]
    ]
    risks = _risks(metrics, language)
    improvements = _improvements(metrics, language)

    return {
        "purpose": t(language, f"purpose_{diagram.get('kind', 'architecture')}"),
        "description": t(language, "described", nodes=len(nodes), edges=len(edges))
        + " "
        + t(language, "generated_offline"),
        "key_components": key_components,
        "patterns": patterns,
        "risks": risks,
        "improvements": improvements,
        "source": "static",
    }


def _risk(
    language: str,
    *,
    severity: str,
    kind: str,
    impact: str,
    effort: str,
    issue: str,
    evidence: list[str],
    location: str = "",
) -> dict[str, Any]:
    """Assemble one fully explained risk.

    A severity on its own is not actionable - the reader has no way to tell
    whether "medium" means "rename a variable" or "restructure a package". Every
    risk therefore carries what was measured, why it matters, what it costs and
    what to do about it, so the card can be read without prior context.
    """
    return {
        "severity": severity,
        "severity_label": t(language, f"severity_{severity}"),
        "title": t(language, f"{kind}_title"),
        "issue": issue,
        "why": t(language, f"{kind}_why"),
        "remediation": t(language, f"{kind}_fix"),
        "impact": t(language, f"impact_{impact}"),
        "effort": t(language, f"effort_{effort}"),
        "evidence": [item for item in evidence if item],
        "location": location or "",
    }


def _risks(metrics: dict[str, Any], language: str) -> list[dict[str, Any]]:
    risks: list[dict[str, Any]] = []
    for cycle in (metrics.get("cycles") or [])[:3]:
        modules = list(cycle.get("modules") or [])
        path = " → ".join(modules + modules[:1]) if modules else ""
        risks.append(
            _risk(
                language,
                severity="high",
                kind="risk_cycle",
                impact="coupling",
                effort="large",
                issue=t(language, "risk_cycle", modules=" → ".join(modules)),
                evidence=[
                    t(language, "evidence_cycle_len", length=cycle.get("length", len(modules))),
                    t(language, "evidence_cycle_path", path=path) if path else "",
                ],
            )
        )
    for god in (metrics.get("god_classes") or [])[:3]:
        risks.append(
            _risk(
                language,
                severity="medium",
                kind="risk_god",
                impact="maintainability",
                effort="medium",
                issue=t(language, "risk_god", name=god["name"], methods=god["methods"]),
                evidence=[
                    t(language, "evidence_god_methods", methods=god.get("methods", 0)),
                    t(language, "evidence_god_props", properties=god.get("properties", 0)),
                    t(language, "evidence_god_deps", dependencies=god.get("dependencies", 0)),
                    t(language, "evidence_file", file=god["file"]) if god.get("file") else "",
                ],
                location=god.get("file", ""),
            )
        )
    for violation in (metrics.get("layering_violations") or [])[:3]:
        risks.append(
            _risk(
                language,
                severity="medium",
                kind="risk_layer",
                impact="layering",
                effort="medium",
                issue=t(
                    language,
                    "risk_layer",
                    src=violation["from"],
                    src_layer=violation["from_layer"],
                    dst=violation["to"],
                    dst_layer=violation["to_layer"],
                ),
                evidence=[
                    t(
                        language,
                        "evidence_layer_edge",
                        kind=violation.get("kind", "depends_on"),
                        src=violation["from"],
                        dst=violation["to"],
                    ),
                    t(language, "evidence_file", file=violation["file"]) if violation.get("file") else "",
                ],
                location=violation.get("file", ""),
            )
        )
    for hub in (metrics.get("hubs") or [])[:2]:
        risks.append(
            _risk(
                language,
                severity="low",
                kind="risk_hub",
                impact="change_risk",
                effort="small",
                issue=t(language, "risk_hub", name=hub["name"], degree=hub["degree"]),
                evidence=[
                    t(language, "evidence_hub_degree", degree=hub.get("degree", 0)),
                    t(language, "evidence_file", file=hub["file"]) if hub.get("file") else "",
                ],
                location=hub.get("file", ""),
            )
        )
    if not risks:
        risks.append(
            _risk(
                language,
                severity="low",
                kind="no_issue",
                impact="none",
                effort="none",
                issue=t(language, "no_issue"),
                evidence=[],
            )
        )
    return risks


def _improvements(metrics: dict[str, Any], language: str) -> list[str]:
    improvements: list[str] = []
    if metrics.get("cycles"):
        improvements.append(t(language, "improve_cycle"))
    if metrics.get("god_classes"):
        improvements.append(t(language, "improve_god"))
    if metrics.get("layering_violations"):
        improvements.append(t(language, "improve_layer"))
    if (metrics.get("abstraction_ratio") or 0) < 0.1:
        improvements.append(t(language, "improve_abstraction"))
    if not improvements:
        improvements.append(t(language, "improve_docs"))
    return improvements


